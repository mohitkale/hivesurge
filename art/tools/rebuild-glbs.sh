#!/usr/bin/env bash
# M3-1c: reproducible GLB rebuild + deterministic diff check.
# Re-exports every model from the procedural source (src/art/catalog.ts) with the pinned
# gltfpack into a scratch tree, then byte-compares against the committed GLBs and
# writes art/models/REBUILD-LOG.md. Exit code 1 if any file differs or is missing.
#   GLTFPACK=/path/to/gltfpack art/tools/rebuild-glbs.sh     (default: npx gltfpack@<pinned>)
#   TSX=/path/to/tsx                                           (default: npx tsx)
set -euo pipefail
cd "$(dirname "$0")/../.."
PIN=$(sed -n "s/.*GLTFPACK_VERSION = '\([0-9.]*\)'.*/\1/p" src/art/catalog.ts)
if [ -z "${GLTFPACK:-}" ]; then
  T=$(mktemp -d); npm --prefix "$T" install --no-save --silent "gltfpack@$PIN" >/dev/null
  GLTFPACK="$T/node_modules/.bin/gltfpack"
fi
TSX=${TSX:-"npx --yes tsx@4"}
SCRATCH=$(mktemp -d)
HS_EXPORT_ROOT="$SCRATCH" GLTFPACK="$GLTFPACK" $TSX art/tools/export-assets.ts >/dev/null
LOG=art/models/REBUILD-LOG.md
fail=0; n=0
{
  echo "# GLB rebuild log (M3-1c)"
  echo
  echo "Generated by \`art/tools/rebuild-glbs.sh\` on $(date -u +%Y-%m-%dT%H:%MZ) at commit \`$(git rev-parse --short HEAD)\`."
  echo "gltfpack: \`$("$GLTFPACK" -h 2>&1 | head -1)\` (npm gltfpack@$PIN) · node $(node -v)."
  echo
  echo "| GLB | committed sha256 | rebuilt sha256 | result |"
  echo "| --- | --- | --- | --- |"
  for f in $(cd "$SCRATCH" && find public/assets/models art/models -name '*.glb' | sort); do
    n=$((n+1))
    new=$(sha256sum "$SCRATCH/$f" | cut -c1-16)
    if [ -f "$f" ]; then old=$(sha256sum "$f" | cut -c1-16); else old=missing; fi
    if [ "$old" = "$new" ]; then r=identical; else r=DIFFERENT; fail=1; fi
    echo "| \`$f\` | \`$old\` | \`$new\` | $r |"
  done
  for f in $(find public/assets/models art/models -name '*.glb' | sort); do
    [ -f "$SCRATCH/$f" ] || { echo "| \`$f\` | committed | not produced | ORPHAN |"; fail=1; }
  done
  echo
  if [ $fail = 0 ]; then echo "**Result: all $n GLBs byte-identical.**"; else echo "**Result: differences found.**"; fi
} > "$LOG"
rm -rf "$SCRATCH"
tail -1 "$LOG"
exit $fail
